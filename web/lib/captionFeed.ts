import type {
    GlossToken,
    SentenceStatus,
    ServerGlossSequenceMessage,
    ServerSentenceMessage,
    ServerState,
} from "./types";
import {
    CAPTION_HISTORY_LIMIT,
    MAX_PARTIAL_GLOSSES,
    SentenceStatus as SentenceStatusMap,
    ServerState as ServerStateMap,
} from "./constants";

// State of the real-time captioning feed (KAN-23).
//
// The Gesture Recognition Service sends these events for one utterance:
//   caption        a sign was recognized (partial result, arrives immediately)
//   gloss_sequence the utterance ended; the ordered signs with confidence
//   sentence       the Armenian sentence generated by the NLP layer (arrives
//                  1-3 seconds later) with a status: ok / partial / fallback
//   unrecognized   a gesture could not be classified
//   state          idle / listening / processing / error
//   error          a processing or connection error
//
// This file is a pure reducer with no React or browser code, so the feed
// logic can be tested on its own. The React hook lives in useCaptionFeed.ts.

/** A recognized sign of the utterance that is still in progress. */
export interface PartialGloss {
    id: number;
    gloss: string;
    confidence: number;
}

/** An utterance that has ended and waits for its sentence. */
export interface PendingUtterance {
    utteranceId: number;
    glosses: GlossToken[];
}

/** A completed caption: the final sentence of one utterance. */
export interface CaptionEntry {
    id: number;
    text: string;
    status: SentenceStatus;
    warnings: string[];
    glosses: string[];
    /** Average confidence of the recognized signs, or null when unknown. */
    confidence: number | null;
}

export interface CaptionFeedState {
    serverState: ServerState;
    /** The user pressed "Finalize" and the server has not answered yet. */
    finalizing: boolean;
    partials: PartialGloss[];
    pending: PendingUtterance[];
    /** Completed captions, newest first. */
    captions: CaptionEntry[];
    unrecognized: boolean;
    error: string | null;
    nextPartialId: number;
}

export const initialCaptionFeedState: CaptionFeedState = {
    serverState: ServerStateMap.IDLE,
    finalizing: false,
    partials: [],
    pending: [],
    captions: [],
    unrecognized: false,
    error: null,
    nextPartialId: 1,
};

export type CaptionFeedAction =
    | { type: "server_state"; state: ServerState }
    | { type: "caption"; gloss: string[]; confidence: number }
    | { type: "unrecognized" }
    | { type: "clear_unrecognized" }
    | { type: "gloss_sequence"; message: ServerGlossSequenceMessage }
    | { type: "sentence"; message: ServerSentenceMessage }
    | { type: "pending_timeout" }
    | { type: "finalize_requested" }
    | { type: "finalize_timeout" }
    | { type: "error"; message: string }
    | { type: "reset" };

export function averageConfidence(glosses: GlossToken[]): number | null {
    if (glosses.length === 0) return null;
    const sum = glosses.reduce((total, g) => total + g.confidence, 0);
    return sum / glosses.length;
}

function addCaption(captions: CaptionEntry[], entry: CaptionEntry): CaptionEntry[] {
    const others = captions.filter((c) => c.id !== entry.id);
    return [entry, ...others].slice(0, CAPTION_HISTORY_LIMIT);
}

export function captionFeedReducer(
    state: CaptionFeedState,
    action: CaptionFeedAction
): CaptionFeedState {
    switch (action.type) {
        case "server_state": {
            const listening = action.state === ServerStateMap.LISTENING;
            return {
                ...state,
                serverState: action.state,
                // The server is ready again: the finalize round trip and any
                // earlier error are over.
                finalizing: listening ? false : state.finalizing,
                error: listening ? null : state.error,
            };
        }

        case "caption": {
            const added = action.gloss.map((gloss, index) => ({
                id: state.nextPartialId + index,
                gloss,
                confidence: action.confidence,
            }));
            return {
                ...state,
                partials: [...state.partials, ...added].slice(-MAX_PARTIAL_GLOSSES),
                nextPartialId: state.nextPartialId + added.length,
                unrecognized: false,
                error: null,
            };
        }

        case "unrecognized":
            // Also ends a finalize that had nothing to recognize.
            return { ...state, unrecognized: true, finalizing: false };

        case "clear_unrecognized":
            return { ...state, unrecognized: false };

        case "gloss_sequence": {
            const { utteranceId, glosses } = action.message;
            const pending = state.pending.filter((p) => p.utteranceId !== utteranceId);
            return {
                ...state,
                // The utterance is complete: its live signs are replaced by
                // the sentence that is being generated.
                partials: [],
                pending: [...pending, { utteranceId, glosses }],
            };
        }

        case "sentence": {
            const { utteranceId, text, status, warnings, glossText } = action.message;
            const known = state.pending.find((p) => p.utteranceId === utteranceId);
            const tokens = known?.glosses ?? [];
            const entry: CaptionEntry = {
                id: utteranceId,
                text,
                status,
                warnings,
                glosses: tokens.length > 0 ? tokens.map((g) => g.gloss) : glossText.split(" ").filter(Boolean),
                confidence: averageConfidence(tokens),
            };
            return {
                ...state,
                pending: state.pending.filter((p) => p.utteranceId !== utteranceId),
                captions: addCaption(state.captions, entry),
                error: null,
            };
        }

        case "pending_timeout": {
            // The sentence never arrived: show the recognized signs instead of
            // waiting forever.
            let captions = state.captions;
            for (const utterance of state.pending) {
                const glosses = utterance.glosses.map((g) => g.gloss);
                captions = addCaption(captions, {
                    id: utterance.utteranceId,
                    text: glosses.join(" "),
                    status: SentenceStatusMap.FALLBACK,
                    warnings: [],
                    glosses,
                    confidence: averageConfidence(utterance.glosses),
                });
            }
            return { ...state, pending: [], captions };
        }

        case "finalize_requested":
            return { ...state, finalizing: true };

        case "finalize_timeout":
            return { ...state, finalizing: false };

        case "error":
            return { ...state, error: action.message, finalizing: false };

        case "reset":
            return initialCaptionFeedState;
    }
}

/**
 * The state shown to the user: idle, listening, processing or error.
 * Generating the sentence does not change it (the camera keeps listening);
 * the caption area shows a separate "generating" indicator for that.
 */
export function deriveRecognitionState(state: CaptionFeedState): ServerState {
    if (state.error || state.serverState === ServerStateMap.ERROR) {
        return ServerStateMap.ERROR;
    }
    if (state.finalizing || state.serverState === ServerStateMap.PROCESSING) {
        return ServerStateMap.PROCESSING;
    }
    return state.serverState;
}
